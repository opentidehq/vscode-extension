// The `opentide` launcher the terminal's PATH carries (SPEC §11). The bundled runtime runs as
// `python -I … -m opentide`, and its console-script shebang names the build machine's path, so the
// extension writes a small script that runs the active runtime exactly as the extension does. vscode-free.
import { createHash } from "node:crypto";
import * as path from "node:path";

export interface LauncherRuntime {
  readonly command: string;
  readonly args: readonly string[];
  readonly env: Readonly<Record<string, string>>;
}

export interface LauncherFile {
  readonly name: string;
  readonly content: string;
  /** POSIX file mode. */
  readonly mode: number;
}

const NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** POSIX `sh` single quoting. */
export function shQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/**
 * `cmd.exe` quoting for a batch file: double quotes, `%` doubled so it is never expanded. A `"` cannot
 * appear in a Windows path, and is refused elsewhere.
 */
export function cmdQuote(value: string): string {
  if (value.includes('"')) throw new Error(`cannot quote ${value} for cmd.exe`);
  return `"${value.replaceAll("%", "%%")}"`;
}

/** The launcher's file(s) for a platform: `opentide` (sh) on POSIX, `opentide.cmd` on Windows. */
export function launcherFiles(runtime: LauncherRuntime, platform: NodeJS.Platform): LauncherFile[] {
  const env = Object.entries(runtime.env).filter(
    ([name]) => NAME.test(name) && name.toUpperCase() !== "PATH",
  );
  if (platform === "win32") {
    const lines = [
      "@echo off",
      "rem Generated by the opentide VS Code extension: runs the opentide runtime it uses.",
      "setlocal",
      ...env.map(([name, value]) => `set ${cmdQuote(`${name}=${value}`)}`),
      `${[runtime.command, ...runtime.args].map(cmdQuote).join(" ")} %*`,
    ];
    return [{ name: "opentide.cmd", content: `${lines.join("\r\n")}\r\n`, mode: 0o755 }];
  }
  const lines = [
    "#!/bin/sh",
    "# Generated by the opentide VS Code extension: runs the opentide runtime it uses.",
    ...env.map(([name, value]) => `${name}=${shQuote(value)}; export ${name}`),
    `exec ${[runtime.command, ...runtime.args].map(shQuote).join(" ")} "$@"`,
  ];
  return [{ name: "opentide", content: `${lines.join("\n")}\n`, mode: 0o755 }];
}

/**
 * The launcher's folder for a runtime: one per runtime under `<globalStorage>/bin/`, so two windows with
 * different runtimes never overwrite each other's.
 */
export function launcherDir(globalStorage: string, runtime: LauncherRuntime): string {
  const id = createHash("sha256")
    .update(JSON.stringify([runtime.command, runtime.args, runtime.env]))
    .digest("hex")
    .slice(0, 12);
  return path.join(globalStorage, "bin", id);
}

/** The name of `PATH` in an environment (`Path` on Windows), and a value with `dir` first. */
export function prependPath(
  env: Readonly<Record<string, string | undefined>>,
  dir: string,
  platform: NodeJS.Platform,
): { key: string; value: string } {
  const key =
    platform === "win32"
      ? (Object.keys(env).find((name) => name.toUpperCase() === "PATH") ?? "PATH")
      : "PATH";
  const delimiter = platform === "win32" ? ";" : ":";
  const current = env[key];
  return { key, value: current ? `${dir}${delimiter}${current}` : dir };
}

/**
 * Whether new integrated terminals get the launcher on PATH (`environmentVariableCollection`): only for the
 * bundled runtime, when no `opentide` is on PATH already, with `opentide.terminal.addToPath` on, trusted.
 */
export function shouldAddToPath(options: {
  readonly source: string | undefined;
  readonly restricted: boolean;
  readonly setting: boolean | undefined;
  readonly opentideOnPath: boolean;
}): boolean {
  return (
    options.setting !== false &&
    options.source === "bundled" &&
    !options.restricted &&
    !options.opentideOnPath
  );
}
