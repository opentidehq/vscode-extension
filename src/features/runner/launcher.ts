// The `opentide` launcher the terminal's PATH carries (SPEC §11). A runtime that runs as
// `python -m opentide` (no console script on PATH, or one a policy does not let run), or the package the
// extension carries (`<node> dist/opentide/cli.js`), has no `opentide` command, so the extension writes
// a small script that runs the active runtime exactly as the extension does. vscode-free.
import { createHash } from "node:crypto";
import * as path from "node:path";

export interface LauncherRuntime {
  readonly command: string;
  readonly args: readonly string[];
  readonly env: Readonly<Record<string, string>>;
}

export interface LauncherFile {
  readonly name: string;
  readonly content: string;
  /** POSIX file mode. */
  readonly mode: number;
}

const NAME = /^[A-Za-z_][A-Za-z0-9_]*$/;

/** POSIX `sh` single quoting. */
export function shQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

/**
 * `cmd.exe` quoting for a batch file: double quotes, `%` doubled so it is never expanded. A `"` cannot
 * appear in a Windows path, and is refused elsewhere.
 */
export function cmdQuote(value: string): string {
  if (value.includes('"')) throw new Error(`cannot quote ${value} for cmd.exe`);
  return `"${value.replaceAll("%", "%%")}"`;
}

/** A Windows path as MSYS bash (Git Bash) takes it: forward slashes, `C:/…`. */
export function msysPath(value: string): string {
  return /^[A-Za-z]:[\\/]/.test(value) || value.startsWith("\\\\") ? value.replaceAll("\\", "/") : value;
}

function shLauncher(command: string, args: readonly string[], env: readonly [string, string][]): string {
  const lines = [
    "#!/bin/sh",
    "# Generated by the opentide VS Code extension: runs the opentide runtime it uses.",
    ...env.map(([name, value]) => `${name}=${shQuote(value)}; export ${name}`),
    `exec ${[command, ...args].map(shQuote).join(" ")} "$@"`,
  ];
  return `${lines.join("\n")}\n`;
}

/** Whether a line reads the same in every OEM code page cmd.exe may use: all of it below 0x80. */
function isAscii(line: string): boolean {
  for (let i = 0; i < line.length; i++) if (line.charCodeAt(i) > 0x7f) return false;
  return true;
}

/**
 * The `opentide.cmd` batch file. The file is UTF-8, but cmd.exe decodes a batch file in the console's code
 * page (an OEM one such as 850 or 932), so a non-ASCII path (`C:\Users\Jörg\…`) would be garbled. cmd.exe
 * reads a batch file line by line, so when a line is not ASCII the script switches the console to UTF-8
 * (65001) for those lines, keeps each token of the command line in a variable, and restores the code
 * page before it runs opentide: its exit code is the script's, and Ctrl+C leaves the code page as it was.
 */
function cmdLauncher(command: string, args: readonly string[], env: readonly [string, string][]): string {
  const sets = env.map(([name, value]) => `set ${cmdQuote(`${name}=${value}`)}`);
  const tokens = [command, ...args];
  const commandLine = tokens.map(cmdQuote).join(" ");
  const ascii = [...sets, commandLine].every(isAscii);
  const lines = [
    "@echo off",
    "rem Generated by the opentide VS Code extension: runs the opentide runtime it uses.",
    "setlocal",
    ...(ascii
      ? [...sets, `${commandLine} %*`]
      : [
          "rem The lines below are UTF-8: read them in code page 65001, then restore the console's own",
          "rem before opentide starts, so that Ctrl+C (Terminate batch job) cannot leave the console in 65001.",
          `for /f "tokens=2 delims=:" %%a in ('chcp') do for /f "tokens=1 delims=. " %%b in ("%%a") do set "OPENTIDE_LAUNCHER_CP=%%b"`,
          "chcp 65001 >nul",
          ...sets,
          // cmd.exe keeps variables in UTF-16: each token read now runs the same in any code page. One
          // variable per token, its NAME=value in one quoted region, so `&` and `^` in a path stay literal.
          ...tokens.map((token, i) => `set ${cmdQuote(`OPENTIDE_LAUNCHER_ARG${i}=${token}`)}`),
          "if defined OPENTIDE_LAUNCHER_CP chcp %OPENTIDE_LAUNCHER_CP% >nul",
          'set "OPENTIDE_LAUNCHER_CP="',
          // The line is expanded before it runs: the variables are cleared and opentide does not inherit
          // them. Each expansion sits inside quotes, and % is expanded once, so a `%` in a path stays one.
          [
            ...tokens.map((_, i) => `set "OPENTIDE_LAUNCHER_ARG${i}="`),
            `${tokens.map((_, i) => `"%OPENTIDE_LAUNCHER_ARG${i}%"`).join(" ")} %*`,
          ].join(" & "),
        ]),
  ];
  return `${lines.join("\r\n")}\r\n`;
}

/**
 * The launcher's file(s) for a platform: `opentide` (sh) on POSIX; on Windows `opentide.cmd` for cmd.exe
 * and PowerShell (through PATHEXT), and next to it an extensionless sh `opentide` for Git Bash, which
 * does not use PATHEXT (as npm's cmd-shim writes).
 */
export function launcherFiles(runtime: LauncherRuntime, platform: NodeJS.Platform): LauncherFile[] {
  const env = Object.entries(runtime.env).filter(
    ([name]) => NAME.test(name) && name.toUpperCase() !== "PATH",
  );
  if (platform === "win32") {
    return [
      { name: "opentide.cmd", content: cmdLauncher(runtime.command, runtime.args, env), mode: 0o755 },
      {
        name: "opentide",
        content: shLauncher(msysPath(runtime.command), runtime.args.map(msysPath), env),
        mode: 0o755,
      },
    ];
  }
  return [{ name: "opentide", content: shLauncher(runtime.command, runtime.args, env), mode: 0o755 }];
}

/**
 * The launcher's folder for a runtime: one per runtime under `<globalStorage>/bin/`, so two windows with
 * different runtimes never overwrite each other's.
 */
export function launcherDir(globalStorage: string, runtime: LauncherRuntime): string {
  const id = createHash("sha256")
    .update(JSON.stringify([runtime.command, runtime.args, runtime.env]))
    .digest("hex")
    .slice(0, 12);
  return path.join(globalStorage, "bin", id);
}

/** The name of `PATH` in an environment (`Path` on Windows), and a value with `dir` first. */
export function prependPath(
  env: Readonly<Record<string, string | undefined>>,
  dir: string,
  platform: NodeJS.Platform,
): { key: string; value: string } {
  const key =
    platform === "win32"
      ? (Object.keys(env).find((name) => name.toUpperCase() === "PATH") ?? "PATH")
      : "PATH";
  const delimiter = platform === "win32" ? ";" : ":";
  const current = env[key];
  return { key, value: current ? `${dir}${delimiter}${current}` : dir };
}

/** Whether a runtime runs opentide as a module of its interpreter (`python -m opentide`). */
export function runsAsModule(args: readonly string[] | undefined): boolean {
  return args !== undefined && args.length >= 2 && args.at(-2) === "-m" && args.at(-1) === "opentide";
}

/**
 * Whether a runtime has no `opentide` command of its own: `python -m opentide`, or the package the
 * extension carries, which runs as `<node> dist/opentide/cli.js` with `ELECTRON_RUN_AS_NODE=1`.
 */
export function needsLauncher(
  runtime: { readonly source?: string; readonly args: readonly string[] } | undefined,
): boolean {
  return runtime !== undefined && (runtime.source === "package" || runsAsModule(runtime.args));
}

/**
 * Whether new integrated terminals get the launcher on PATH (`environmentVariableCollection`): only for a
 * runtime with no `opentide` command of its own ({@link needsLauncher}), when no `opentide` is on PATH already, with
 * `opentide.terminal.addToPath` on, trusted.
 */
export function shouldAddToPath(options: {
  readonly module: boolean;
  readonly restricted: boolean;
  readonly setting: boolean | undefined;
  readonly opentideOnPath: boolean;
}): boolean {
  return options.setting !== false && options.module && !options.restricted && !options.opentideOnPath;
}
