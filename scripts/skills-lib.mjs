// Pure helpers for scripts/skills.mjs: the opentide skills (opentidehq/skills, EUPL-1.2) the extension contributes
// to VS Code's agents through `contributes.chatSkills` (SPEC §12). The upstream tree is pinned by commit and by a
// digest of its content: GitHub's archive bytes are not promised to be stable, the files of a commit are.
import { createHash } from "node:crypto";
import { GrammarError, sha256 } from "./grammars-lib.mjs";

export class SkillsError extends GrammarError {}

/** The context key the extension sets when the opentidehq/skills Agent Plugin supplies the skills (#6). */
export const PLUGIN_CONTEXT_KEY = "opentide.skillsFromPlugin";

/** Where the skills go in this repository and in the package. */
export const SKILLS_DIR = "skills";

/**
 * The files of the upstream tree this extension takes, by path inside the repository: `skills/**` (each skill's
 * SKILL.md and its `references/`) and the LICENSE. Strips the archive's top directory (`skills-<sha>/`).
 */
export function upstreamFiles(archive) {
  const names = [...archive.keys()];
  const top = names[0]?.split("/")[0];
  if (!top || names.some((name) => name.split("/")[0] !== top))
    throw new SkillsError("the archive has no single top directory");
  const files = new Map();
  for (const [name, data] of archive) {
    const path = name.slice(top.length + 1);
    if (path === "LICENSE" || path.startsWith("skills/")) files.set(path, data);
  }
  if (!files.has("LICENSE")) throw new SkillsError("the archive has no LICENSE");
  return files;
}

/**
 * A digest of the content: SHA-256 over `<sha256 of the file>  <path>` lines, paths sorted. The same for the files
 * of a commit however they were packed.
 */
export function contentDigest(files) {
  const lines = [...files.keys()]
    .sort()
    .map((path) => `${sha256(files.get(path))}  ${path}\n`)
    .join("");
  return createHash("sha256").update(lines).digest("hex");
}

/** The frontmatter `name` and `description` of a SKILL.md (the Agent Skills format: YAML between `---` lines). */
export function frontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(text);
  if (!match) return {};
  const field = (key) => {
    const line = new RegExp(`^${key}:[ \\t]*(.*)$`, "m").exec(match[1]);
    return line?.[1]?.trim().replace(/^(["'])(.*)\1$/, "$2");
  };
  return { name: field("name"), description: field("description") };
}

/**
 * The skills of the tree, checked against what VS Code requires of a contributed skill: a folder with a SKILL.md
 * whose `name` is the folder's name (lowercase letters, digits and hyphens, up to 64) and a description (up to
 * 1024 characters): an invalid one is skipped silently by VS Code, so it is an error here.
 */
export function skillNames(files) {
  const names = new Set();
  for (const path of files.keys()) {
    const match = /^skills\/([^/]+)\/SKILL\.md$/.exec(path);
    if (match?.[1]) names.add(match[1]);
  }
  for (const name of [...names].sort()) {
    const { name: declared, description } = frontmatter(
      files.get(`skills/${name}/SKILL.md`).toString("utf8"),
    );
    if (declared !== name) throw new SkillsError(`skills/${name}/SKILL.md names itself "${declared ?? ""}"`);
    if (!/^[a-z0-9-]{1,64}$/.test(name)) throw new SkillsError(`"${name}" is not a valid skill name`);
    if (!description || description.length > 1024)
      throw new SkillsError(`skills/${name}/SKILL.md has no description, or one over 1024 characters`);
  }
  if (names.size === 0) throw new SkillsError("the archive has no skills");
  return [...names].sort();
}

/** `contributes.chatSkills`: one entry per skill, off while the Agent Plugin supplies them. */
export function chatSkillEntries(names) {
  return names.map((name) => ({
    path: `./${SKILLS_DIR}/${name}/SKILL.md`,
    when: `!${PLUGIN_CONTEXT_KEY}`,
  }));
}

/** What `npm run skills` writes: the files under skills/, and contrib/skills.json's text. */
export function skillsOutputs(pin, files) {
  const names = skillNames(files);
  const outputs = new Map();
  for (const [path, data] of files) {
    outputs.set(path === "LICENSE" ? `${SKILLS_DIR}/LICENSE` : path, data);
  }
  const fragment = {
    $comment: `Generated by scripts/skills.mjs from opentidehq/skills@${pin.commit.slice(0, 12)}. Do not edit.`,
    contributes: { chatSkills: chatSkillEntries(names) },
  };
  return { names, outputs, manifestText: `${JSON.stringify(fragment, null, 2)}\n` };
}
