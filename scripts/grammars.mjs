#!/usr/bin/env node
// Copies the TextMate grammars from the language-server highlights zip (and the TOML grammar) into
// syntaxes/, and writes contrib/grammars.json, which `npm run manifest` merges into package.json.
// Both downloads are checked against the SHA-256 in pins.json.
//   node scripts/grammars.mjs                     download (cached in .cache/), verify, write
//   node scripts/grammars.mjs --zip <file>        use a local highlights zip
//   node scripts/grammars.mjs --toml <file>       use a local TOML grammar
//   node scripts/grammars.mjs --check             fail when syntaxes/ or contrib/grammars.json differ
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { GrammarError, readZip, transformHighlights, transformToml, verifySha256 } from "./grammars-lib.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const option = (flag) => {
  const index = args.indexOf(flag);
  return index >= 0 ? args[index + 1] : undefined;
};
const check = args.includes("--check");

async function fetchCached(url, name) {
  const cache = join(root, ".cache");
  const path = join(cache, name);
  if (existsSync(path)) return readFileSync(path);
  const response = await fetch(url, { redirect: "follow" });
  if (!response.ok) throw new GrammarError(`GET ${url}: HTTP ${response.status}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  mkdirSync(cache, { recursive: true });
  writeFileSync(path, buffer);
  return buffer;
}

async function main() {
  const pins = JSON.parse(readFileSync(join(root, "pins.json"), "utf8"));
  const { version, url, sha256 } = pins.highlights;
  const zipPath = option("--zip");
  const zip = zipPath ? readFileSync(zipPath) : await fetchCached(url, `highlights-v${version}.zip`);
  verifySha256(zip, sha256, `highlights-v${version}.zip`);
  const files = readZip(zip);
  const { outputs, grammars } = transformHighlights(files);

  const tomlPath = option("--toml");
  const tomlRaw = tomlPath
    ? readFileSync(tomlPath)
    : await fetchCached(pins.tomlGrammar.url, `toml-${pins.tomlGrammar.sha256.slice(0, 12)}.tmLanguage.json`);
  verifySha256(tomlRaw, pins.tomlGrammar.sha256, "TOML grammar");
  const toml = transformToml(tomlRaw);
  outputs.set("opentide-config.tmLanguage.json", toml.text);
  grammars.push(toml.entry);

  for (const legal of ["LICENSE", "NOTICE"]) {
    const data = files.get(legal);
    if (!data) throw new GrammarError(`highlights zip has no ${legal}`);
    outputs.set(`${legal}.language-server`, data.toString("utf8"));
  }

  const fragment = {
    $comment: `Generated by scripts/grammars.mjs from highlights-v${version}.zip. Do not edit.`,
    contributes: { grammars },
  };
  const writes = new Map([...outputs].map(([name, text]) => [join(root, "syntaxes", name), text]));
  writes.set(join(root, "contrib", "grammars.json"), `${JSON.stringify(fragment, null, 2)}\n`);

  const stale = [...writes].filter(
    ([path, text]) => !existsSync(path) || readFileSync(path, "utf8") !== text,
  );
  if (check) {
    if (stale.length > 0) {
      console.error(`grammars are stale: ${stale.map(([path]) => path.slice(root.length + 1)).join(", ")}`);
      console.error("Run `npm run grammars && npm run manifest`.");
      process.exit(1);
    }
    console.log(`grammars match highlights-v${version}.zip`);
    return;
  }
  mkdirSync(join(root, "syntaxes"), { recursive: true });
  for (const [path, text] of stale) writeFileSync(path, text);
  console.log(`wrote ${stale.length} file(s) from highlights-v${version}.zip; now run \`npm run manifest\``);
}

main().catch((error) => {
  if (error instanceof GrammarError) {
    console.error(`grammars: ${error.message}`);
    process.exit(1);
  }
  throw error;
});
