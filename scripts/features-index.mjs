#!/usr/bin/env node
// Generates src/features/index.generated.ts: one import per src/features/<id>/index.ts, sorted by id.
// The file is not committed, so features added in parallel never conflict on it.
//   node scripts/features-index.mjs          write it
//   node scripts/features-index.mjs --check  fail when it is stale
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const featuresDir = join(root, "src", "features");
const out = join(featuresDir, "index.generated.ts");

const FEATURE_ID = /^[a-z][a-z0-9-]*$/;

/** Feature folder names under `dir` that contain an index.ts, sorted. */
export function featureIds(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isDirectory() && existsSync(join(dir, name, "index.ts")))
    .sort();
}

export function render(ids) {
  for (const id of ids) {
    if (!FEATURE_ID.test(id)) throw new Error(`feature folder "${id}" must match ${FEATURE_ID}`);
  }
  const ident = (id) => `feature_${id.replaceAll("-", "_")}`;
  const lines = [
    "// Generated by scripts/features-index.mjs from src/features/*/index.ts. Do not edit.",
    'import type { Feature } from "../core/feature";',
    ...ids.map((id) => `import ${ident(id)} from "./${id}/index";`),
    "",
    "export const features: readonly Feature[] = [",
    ...ids.map((id) => `  ${ident(id)},`),
    "];",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = render(featureIds(featuresDir));
  const current = existsSync(out) ? readFileSync(out, "utf8") : undefined;
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("src/features/index.generated.ts is stale; run `npm run features`.");
      process.exit(1);
    }
  } else if (current !== next) {
    // A fresh clone has no src/features/ until a feature lands: git keeps no empty folder.
    mkdirSync(featuresDir, { recursive: true });
    writeFileSync(out, next);
  }
}
